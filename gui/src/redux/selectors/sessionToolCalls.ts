import { Tool, ToolStatus } from "core";
import { filterActiveTools } from "./selectActiveTools";
import type { ChatHistoryItemWithMessageId } from "../slices/sessionHistory";
import type { RootState } from "../store";
import {
  findAllCurToolCalls,
  findAllCurToolCallsByStatus,
  findToolCallById,
  hasCurrentToolCalls,
} from "../util";

/**
 * Phase 1 session-scoped tool-call selectors (方案.md §五.9).
 *
 * The legacy `selectToolCalls.ts` selectors read `state.session`, i.e. the
 * active session. Streams, approvals and paging must never do that: every
 * caller passes the session it owns.
 *
 * These are plain functions, not `createSelector`: RTK's default memoizer has
 * a cache size of one, so a selector keyed by `(state, sessionId)` would thrash
 * between tabs and hide stale reads. The scans are over a single session's
 * history and cheap enough to run per render.
 */

export function selectSessionHistory(
  state: RootState,
  sessionId: string,
): ChatHistoryItemWithMessageId[] {
  return state.sessions.sessionsById[sessionId]?.history ?? [];
}

export function selectSessionHasToolCalls(
  state: RootState,
  sessionId: string,
): boolean {
  return hasCurrentToolCalls(selectSessionHistory(state, sessionId));
}

export function selectSessionToolCalls(state: RootState, sessionId: string) {
  return findAllCurToolCalls(selectSessionHistory(state, sessionId));
}

export function selectSessionToolCallsByStatus(
  state: RootState,
  sessionId: string,
  status: ToolStatus,
) {
  return findAllCurToolCallsByStatus(
    selectSessionHistory(state, sessionId),
    status,
  );
}

/** Tool calls generated by the model and not yet executed. */
export function selectSessionPendingToolCalls(
  state: RootState,
  sessionId: string,
) {
  return selectSessionToolCallsByStatus(state, sessionId, "generated");
}

export function selectSessionFirstPendingToolCall(
  state: RootState,
  sessionId: string,
) {
  return selectSessionPendingToolCalls(state, sessionId)[0] || undefined;
}

export function selectSessionToolCallById(
  state: RootState,
  sessionId: string,
  toolCallId: string,
) {
  return findToolCallById(selectSessionHistory(state, sessionId), toolCallId);
}

/**
 * Tools available to a session's own request (方案.md §五.20).
 *
 * The legacy `selectActiveTools` read the active tab's mode from the legacy
 * tab's mode. A background session must use its own mode and the shared global
 * tool/policy configuration.
 */
export function selectSessionActiveTools(
  state: RootState,
  sessionId: string,
): Tool[] {
  const mode = state.sessions.sessionsById[sessionId]?.mode;
  if (!mode) {
    return [];
  }
  return filterActiveTools(
    mode,
    state.config.config.tools,
    state.ui.toolSettings,
    state.ui.toolGroupSettings,
  );
}
